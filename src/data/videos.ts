// Demo catalogue for the Video tab (Netflix-like streaming, matching walrus/docs/schema/schema-examples/movies.yml).
// Each film has genres, director, release year, runtime, age rating, whether it is a platform
// original, popularity (views in millions), community rating, and synopsis.

function v(
  id: string,
  title: string,
  director: string,
  year: number,
  genres: string[],
  runtimeMin: number,
  ageRating: number,
  original: boolean,
  views: number,
  communityRating: number,
  synopsis: string,
): Video {
  return {
    id,
    title,
    director,
    year,
    genres,
    runtimeMin,
    ageRating,
    original,
    views,
    communityRating,
    userRating: null,
    synopsis,
  }
}

